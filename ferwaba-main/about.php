                    <h2>Our Story</h2>
                    <p>Founded in 2020, Inkingi Art Space emerged from a vision to create a vibrant cultural hub dedicated to showcasing contemporary African art and fostering creative dialogue within our community. The name "Inkingi" means "bridge" in Kinyarwanda, reflecting our mission to bridge cultures, celebrate diversity, and create meaningful connections through the power of art.</p>
                    <p>What started as a small gallery space has grown into a comprehensive platform that supports emerging and established African artists, hosts thought-provoking exhibitions, and provides educational programs that make art accessible to everyone.</p>
                    <p>Today, we are proud to be recognized as one of the leading contemporary art spaces in our region, having hosted over 25 exhibitions, supported 45+ artists, and welcomed thousands of visitors from around the world.</p>
